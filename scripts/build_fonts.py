"""Builds the two bundled fonts.

- Material Symbols Rounded, subset to the icons the app uses (src/app/ui/icon-names.json).
  Glyphs are addressed by codepoint, not ligature, so the subset stays small.
- Google Sans Flex (latin + latin-ext), with unused axes pinned.

Run: python3 scripts/build_fonts.py  (needs fonttools and brotli)
"""
import json, os, sys
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public/fonts')
os.makedirs(OUT, exist_ok=True)

def symbol_map(font):
    cmap = font.getBestCmap()
    rev = {v: k for k, v in cmap.items()}
    names = {}
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for st in lookup.SubTable:
            if hasattr(st, 'ExtSubTable'):
                st = st.ExtSubTable
            if st.__class__.__name__ != 'LigatureSubst':
                continue
            for first, ligs in st.ligatures.items():
                for lig in ligs:
                    comps = [first] + lig.Component
                    if all(g in rev for g in comps):
                        name = ''.join(chr(rev[g]) for g in comps)
                        cp = rev.get(lig.LigGlyph)
                        if cp and cp >= 0xE000:
                            names[name] = cp
    return names

def build_symbols():
    src = os.path.join(ROOT, 'node_modules/material-symbols/material-symbols-rounded.woff2')
    wanted = sorted(set(json.load(open(os.path.join(ROOT, 'src/app/ui/icon-names.json')))))
    font = TTFont(src)
    mapping = symbol_map(font)
    missing = [n for n in wanted if n not in mapping]
    if missing:
        print('Unknown icons:', ', '.join(missing), file=sys.stderr)
        sys.exit(1)
    font = instancer.instantiateVariableFont(font, {'GRAD': 0, 'opsz': (20, 24), 'wght': (300, 600)})
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = []
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[mapping[n] for n in wanted])
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(os.path.join(OUT, 'symbols.woff2'))
    ts = ['// Generated by scripts/build_fonts.py. Do not edit.', 'export const ICONS = {']
    for n in wanted:
        ts.append(f"  {n}: 0x{mapping[n]:x},")
    ts.append('} as const;\n')
    ts.append('export type IconName = keyof typeof ICONS;\n')
    open(os.path.join(ROOT, 'src/app/ui/icon-codepoints.ts'), 'w').write('\n'.join(ts))
    print('symbols.woff2', os.path.getsize(os.path.join(OUT, 'symbols.woff2')), 'bytes,', len(wanted), 'icons')

def build_sans():
    base = os.path.join(ROOT, 'node_modules/@fontsource-variable/google-sans-flex/files')
    for part in ('latin', 'latin-ext'):
        font = TTFont(os.path.join(base, f'google-sans-flex-{part}-full-normal.woff2'))
        font = instancer.instantiateVariableFont(font, {'wdth': (100, 100), 'slnt': (0, 0), 'GRAD': (0, 0), 'wght': (300, 800)})
        font.flavor = 'woff2'
        out = os.path.join(OUT, f'google-sans-flex-{part}.woff2')
        font.save(out)
        print(os.path.basename(out), os.path.getsize(out), 'bytes')

build_symbols()
build_sans()
