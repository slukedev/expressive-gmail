// Captures the preview in many states for design review: node scripts/capture.mjs <outDir> [filter]
import { chromium } from '@playwright/test';
const out = process.argv[2];
const only = process.argv[3];
const BASE = `http://localhost:${Number(process.env.PREVIEW_PORT) || 5199}/`;
const browser = await chromium.launch();

async function shot(name, { width = 1440, height = 900, dark = false, settings = {}, hash = '#inbox', query = '', act } = {}) {
  if (only && !name.includes(only)) return;
  const ctx = await browser.newContext({ viewport: { width, height }, colorScheme: dark ? 'dark' : 'light', deviceScaleFactor: 1 });
  await ctx.addInitScript((s) => localStorage.setItem('bg.settings.v1', JSON.stringify({ onboarded: true, ...s })), settings);
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  await page.goto(`${BASE}${query}${hash}`);
  await page.waitForSelector('.app', { timeout: 15000 });
  await page.waitForTimeout(1200);
  if (act) await act(page).catch((e) => errors.push(`act: ${e.message.split('\n')[0]}`));
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${out}/${name}.png` });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  console.log(name, errors.length ? `ERRORS: ${errors.join(' | ').slice(0, 300)}` : 'ok', overflow > 0 ? `OVERFLOW ${overflow}` : '');
  await ctx.close();
}

